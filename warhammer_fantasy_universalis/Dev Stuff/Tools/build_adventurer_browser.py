#!/usr/bin/env python3
"""Build the adventurer collection from live presence modifiers and arrival lore.

No adventurers are created or moved. The two browsers preserve one another's
marked insertions in the native decisions view. Run the artifact builder first.
"""
import argparse
import importlib.util
from pathlib import Path
import re
import sys

sys.dont_write_bytecode = True
SPEC = importlib.util.spec_from_file_location("artifact_builder", Path(__file__).with_name("build_artifact_browser.py"))
shared = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(shared)
ROOT = shared.ROOT
BEGIN = "\t\t# BEGIN GENERATED WAR ADVENTURER BROWSER"
END = "\t\t# END GENERATED WAR ADVENTURER BROWSER"
NOTICE = "# Generated by Dev Stuff/Tools/build_adventurer_browser.py. Edit the builder, then regenerate.\n"

# Alphabetical by displayed name. Travelling pairs occupy a single entry.
ROSTER = [
    "abhorash", "gelt", "bardin", "snikch", "elspeth", "gor_rok",
    "gotrek_felix", "grombrindal", "harald", "bugman", "malakai", "wulfhart",
    "nakai", "repanse", "sienna", "teclis", "thanquol", "tyrion",
]
COLOR_VARIANTS = {slug: f"gfx/interface/adventurer_browser/{slug}_color.dds"
                  for slug in ("bugman", "gotrek_felix")}
HIDDEN_BENEFITS = frozenset({"province_trade_power_modifier"})
LABELS = shared.MODIFIERS | {
    "yearly_innovativeness": ("Yearly Innovativeness", False, False),
    "inflation_reduction": ("Yearly Inflation Reduction", False, False),
    "province_trade_power_modifier": ("Local Trade Power", True, False),
    "local_unrest": ("Local Unrest", False, True),
    "global_spy_defence": ("Foreign Spy Detection", True, False),
    "trade_value_modifier": ("Local Trade Value", True, False),
    "army_tradition": ("Yearly Army Tradition", False, False),
    "local_monthly_devastation": ("Monthly Local Devastation", False, True),
    "local_build_cost": ("Local Construction Cost", True, True),
    "local_build_time": ("Local Construction Time", True, True),
    "local_great_project_upgrade_cost": ("Local Great Project Upgrade Cost", True, True),
    "local_great_project_upgrade_time": ("Local Great Project Upgrade Time", True, True),
    "allowed_num_of_buildings": ("Local Building Slots", False, False),
    "allowed_num_of_manufactories": ("Local Manufactory Slots", False, False),
}


def read_data():
    source = re.sub(r"#.*", "", (ROOT / "common/event_modifiers/war_adventurer_modifiers.txt").read_text())
    modifiers = {name.removeprefix("war_adventurer_"): re.findall(r"(\w+)\s*=\s*(-?[\d.]+)", body)
                 for name, body in re.findall(r"(war_adventurer_\w+)\s*=\s*\{([^{}]*)\}", source)}
    assert set(modifiers) == set(ROSTER) and len(ROSTER) == len(set(ROSTER)) == 18
    loc = dict(re.findall(r'^\s*([\w.]+):0\s+"(.*)"',
                         (ROOT / "localisation/war_adventurers_l_english.yml").read_text(encoding="utf-8-sig"), re.M))
    pictures = dict(re.findall(r'name\s*=\s*"(WAR_ADVENTURER_\w+)"\s+texturefile\s*=\s*"([^"]+)"',
                               (ROOT / "interface/war_eventpictures.gfx").read_text()))
    setup = (ROOT / "events/War_Adventurer_Setup.txt").read_text()
    result = {}
    for slug in ROSTER:
        assert f"save_global_event_target_as = war_adventurer_location_{slug}" in setup
        event = (ROOT / f"events/War_Adventurer_{slug}.txt").read_text()
        picture = re.search(r"picture\s*=\s*(\w+)", event)[1]
        texture = COLOR_VARIANTS.get(slug, pictures[picture])
        assert (ROOT / texture).is_file(), texture
        name = re.sub(r", Adventurers?$", "", loc[f"war_adventurer_{slug}"])
        # Arrival notices have an introduction, then two sentences of established
        # character lore. Reuse that paragraph without location-dependent text.
        lore = loc[f"war_adventurer_{slug}.21.d"].split(r"\n\n")[-1]
        assert len(re.split(r"(?<=[.!?])\s+", lore)) == 2 and "[" not in lore
        result[slug] = {"name": name, "lore": lore, "values": modifiers[slug], "texture": texture, "picture": picture}
    assert [result[s]["name"].casefold() for s in ROSTER] == sorted(result[s]["name"].casefold() for s in ROSTER)
    return result


def decorative_icon(name, sprite, x, y):
    return f'''\t\t\ticonType = {{
\t\t\t\tname = "{name}"
\t\t\t\tspriteType = "{sprite}"
\t\t\t\tposition = {{ x = {x} y = {y} }}
\t\t\t\talwaystransparent = yes
\t\t\t}}
'''


def build(game):
    data = read_data()
    loc = {
        "war_adventurer_browser_open_label": "Adventurers",
        "war_adventurer_browser_open_tt": "Open the adventurer collection.",
        "war_adventurer_browser_title": "Adventurers of the World",
        "war_adventurer_browser_close_tt": "Close the adventurer collection.",
        "war_adventurer_browser_refresh_label": "Refresh",
        "war_adventurer_browser_refresh_tt": "Refresh adventurer locations.",
        "war_adventurer_browser_missing_location": "The current location of this adventurer is unknown.",
    }
    gui = [BEGIN + "\n", shared.button("war_adventurer_browser_open", "GFX_standard_button_105", 409, 400,
            '\t\t\t\tbuttonText = "war_adventurer_browser_open_label"\n\t\t\t\tbuttonFont = "vic_18"\n'), '''
\t\twindowType = {
\t\t\tname = "war_adventurer_browser_window"
\t\t\tscripted = yes
\t\t\tposition = { x = 554 y = 0 }
\t\t\tsize = { x = 784 y = 660 }
\t\t\tmoveable = 1
\t\t\tOrientation = "UPPER_LEFT"
''', decorative_icon("war_adventurer_browser_background", "GFX_war_artifact_browser_background", 0, 0),
        decorative_icon("war_adventurer_browser_title_banner", "GFX_diploconfirm_banner", 127, 1),
        decorative_icon("war_adventurer_browser_title_flourish", "GFX_hints_gold_ornament", 273, 45),
        shared.text_box("war_adventurer_browser_title", 147, 15, 490, 36, "war_adventurer_browser_title", "vic_29s"),
        shared.button("war_adventurer_browser_close", "GFX_closebutton2", 743, 10),
        shared.button("war_adventurer_browser_refresh", "GFX_standard_button_105", 339, 620,
            '\t\t\t\tbuttonText = "war_adventurer_browser_refresh_label"\n\t\t\t\tbuttonFont = "vic_18"\n')]
    custom = [NOTICE + '''custom_button = {
    name = war_adventurer_browser_open
    potential = { ai = no }
    trigger = { }
    tooltip = war_adventurer_browser_open_tt
    effect = {
        hidden_effect = {
            if = {
                limit = { NOT = { has_country_flag = war_adventurer_browser_open } }
                war_adventurer_browser_rebuild_locations = yes
            }
            clr_country_flag = war_artifact_browser_open
            set_country_flag = war_adventurer_browser_open
        }
    }
}
custom_window = {
    name = war_adventurer_browser_window
    potential = { ai = no has_country_flag = war_adventurer_browser_open }
}
custom_button = {
    name = war_adventurer_browser_close
    potential = { always = yes }
    trigger = { }
    tooltip = war_adventurer_browser_close_tt
    effect = { clr_country_flag = war_adventurer_browser_open }
}
custom_button = {
    name = war_adventurer_browser_refresh
    potential = { always = yes }
    trigger = { }
    tooltip = war_adventurer_browser_refresh_tt
    effect = { hidden_effect = { war_adventurer_browser_rebuild_locations = yes } }
}
''']
    gfx = [NOTICE + '''spriteTypes = {
    corneredTileSpriteType = {
        name = "GFX_war_adventurer_browser_frame"
        texturefile = "gfx/interface/icon_link_frame.dds"
        size = { x = 228 y = 62 }
        borderSize = { x = 12 y = 12 }
    }
''']
    dynamic = [NOTICE, shared.report_location("war_adventurer_browser", "GetWarAdventurerBrowserReportLocation", loc)]
    events = [NOTICE, "namespace = war_adventurer_browser\n\n"]
    cache = [NOTICE + "# Rebind existing presence modifiers only, on explicit open/refresh.\n"
             "# Upgrade existing presence to survive ownership changes; never create missing travellers.\n"
             "# No movement, encounters, placement, or per-frame world scans.\n"
             "war_adventurer_browser_rebuild_locations = {\n"]
    cache += [f"    clear_global_event_target = war_adventurer_location_{s}\n" for s in ROSTER]
    cache.append("    every_province = {\n")
    for index, slug in enumerate(ROSTER):
        entry = data[slug]
        key = f"war_adventurer_browser_{slug}"
        target = f"war_adventurer_location_{slug}"
        mod = f"war_adventurer_{slug}"
        function = f"GetWarAdventurerBrowserLocation{index + 1}"
        x, y = 40 + (index % 3) * 240, 86 + (index // 3) * 86
        # The native 512x132 event pictures retain their panoramic aspect ratio.
        # Every portrait uses the normal color shader, never an ownership state.
        gui.append(shared.button(key, f"GFX_{key}", x, y, "\t\t\t\tscale = 0.4375\n"))
        gui.append(decorative_icon(key + "_frame", "GFX_war_adventurer_browser_frame", x - 2, y - 2))
        gui.append(shared.text_box(key + "_caption", x - 8, y + 63, 240, 24, key + "_caption", "vic_18"))
        custom.append(f'''custom_button = {{
    name = {key}
    potential = {{ always = yes }}
    tooltip = {key}_tt
''' + shared.report_click("war_adventurer_browser", target, mod, index + 1, "war_adventurer_browser_rebuild_locations") + "}\n")
        gfx.append(f'''    spriteType = {{
        name = "GFX_{key}"
        texturefile = "{entry['texture']}"
        effectFile = "gfx/FX/buttonstate.lua"
        transparencecheck = no
        loadType = "INGAME"
    }}
''')
        loc[key + "_caption"] = entry["name"]
        loc[key + "_tt"] = (f"§Y{entry['name']}§!\\n\\n{shared.benefits(entry['values'], LABELS, HIDDEN_BENEFITS)}"
                            f"\\n\\n{entry['lore']}\\n\\n[Root.{function}]")
        loc[key + "_located"] = shared.location_text(target)
        loc[key + "_unowned_location"] = shared.location_text(target, owned=False)
        loc[key + "_report_title"] = entry["name"]
        loc[key + "_report_desc"] = f"{entry['lore']}\\n\\n[Root.GetWarAdventurerBrowserReportLocation]"
        loc[key + "_unlocated_desc"] = f"{entry['lore']}\\n\\n[Root.{function}]"
        events.append(shared.report_events("war_adventurer_browser", key, index + 1, entry["picture"], entry["name"]))
        dynamic.append(f'''defined_text = {{
    name = {function}
    random = no
    text = {{
        localisation_key = {key}_located
        trigger = {{ exists = event_target:{target} event_target:{target} = {{ has_province_modifier = {mod} owner = {{ always = yes }} }} }}
    }}
    text = {{
        localisation_key = {key}_unowned_location
        trigger = {{ exists = event_target:{target} event_target:{target} = {{ has_province_modifier = {mod} }} }}
    }}
    text = {{ localisation_key = war_adventurer_browser_missing_location }}
}}
''')
        cache.append(f'''        if = {{
            limit = {{ has_province_modifier = {mod} }}
            remove_province_modifier = {mod}
            add_permanent_province_modifier = {{ name = {mod} duration = -1 }}
            save_global_event_target_as = {target}
        }}
''')
    gui.append("\t\t}\n" + END + "\n")
    gfx.append("}\n")
    cache.append("    }\n}\n")
    host = ROOT / "interface/countrydecisionsview.gui"
    baseline = host.read_text()
    assert shared.BEGIN in baseline, "Build the artifact browser first"
    if BEGIN in baseline:
        before, rest = baseline.split(BEGIN, 1)
        _, after = rest.split(END, 1)
        baseline = before + after.lstrip("\n")
    anchor = "\t\t### Select new policy window."
    assert baseline.count(anchor) == 1
    baseline = baseline.replace(anchor, "".join(gui) + anchor)
    localisation = "l_english:\n" + NOTICE
    for key, value in loc.items():
        assert '"' not in value and "\n" not in value and "$" not in value
        localisation += f' {key}:0 "{value}"\n'
    outputs = {
        "interface/countrydecisionsview.gui": baseline,
        "interface/war_adventurer_browser.gfx": "".join(gfx),
        "common/custom_gui/war_adventurer_browser.txt": "".join(custom),
        "customizable_localization/war_adventurer_browser.txt": "".join(dynamic),
        "common/scripted_effects/war_adventurer_browser_effects.txt": "".join(cache),
        "events/War_Adventurer_Browser.txt": "".join(events),
    }
    result = {path: value.encode("utf-8") for path, value in outputs.items()}
    result["localisation/war_adventurer_browser_l_english.yml"] = localisation.encode("utf-8-sig")
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--game-dir", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = build(args.game_dir)
    for name, data in outputs.items():
        path = ROOT / name
        if args.check:
            assert path.read_bytes() == data, f"Regenerate {name}"
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print(f"{'Verified' if args.check else 'Generated'} {len(outputs)} files; all 18 adventurers covered with live modifier bonuses and existing lore.")


if __name__ == "__main__":
    main()
