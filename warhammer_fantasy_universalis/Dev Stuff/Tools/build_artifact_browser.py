def modifier_id(artifact: str) -> str:
    return "location_of_" + ("" if artifact == "nagashs_tome" else "the_") + artifact


def read_modifiers() -> dict[str, list[tuple[str, str]]]:
    source = (ROOT / "common/event_modifiers/war_artifacts.txt").read_text()
    source = re.sub(r"#.*", "", source)
    result = {}
    for name, body in re.findall(r"(location_of_\w+)\s*=\s*\{([^{}]*)\}", source):
        values = re.findall(r"(\w+)\s*=\s*(-?[\d.]+)", body)
        if not values:
            raise ValueError(f"No numeric benefits found for {name}")
        result[name] = values
    return result


def benefits(values: list[tuple[str, str]], labels: dict = MODIFIERS,
             hidden: frozenset[str] = frozenset()) -> str:
    output = []
    for key, raw in values:
        if key in hidden:
            continue
        label, percent, inverted = labels[key]  # Fail on unsupported modifiers.
        value = Decimal(raw)
        good = value < 0 if inverted else value > 0
        display = value * (100 if percent else 1)
        if key == "reduced_liberty_desire":
            display = -display
            percent = True  # Positive script value reduces liberty desire by points.
        number = format(display, "+f").rstrip("0").rstrip(".") if "." in format(display, "+f") else format(display, "+f")
        output.append(f"{label}: §{'G' if good else 'R'}{number}{'%' if percent else ''}§!")
    return "; ".join(output)


def location_text(target: str, owned: bool = True) -> str:
    """Province, owner, superregion; native province localization stays live."""
    owner = f"[{target}.Owner.GetName]" if owned else "Unowned"
    return f"§Y[{target}.GetName]§!, §Y{owner}§!, §Y[{target}.GetSuperRegionName]§!"


def report_click(prefix: str, target: str, modifier: str, number: int, rebuild: str) -> str:
    """Snapshot a valid province in this click's event scope, never a global selection."""
    present = f"exists = event_target:{target} event_target:{target} = {{ has_province_modifier = {modifier} }}"
    # NOT negates each child in EU4; group the conjunction before negating it.
    return f'''    trigger = {{ }}
    effect = {{
        hidden_effect = {{
            if = {{
                limit = {{ NOT = {{ AND = {{ {present} }} }} }}
                {rebuild} = yes
            }}
            clr_country_flag = {prefix}_open
            if = {{
                limit = {{ {present} }}
                event_target:{target} = {{ save_event_target_as = {prefix}_province }}
                country_event = {{ id = {prefix}.{number} }}
            }}
            else = {{ country_event = {{ id = {prefix}.{100 + number} }} }}
        }}
    }}
'''


def report_events(prefix: str, key: str, number: int, picture: str, title: str) -> str:
    """Separate absent reports have no Go To arrow, so they cannot point at stale land."""
    output = []
    for located in (True, False):
        goto = f"    goto = {prefix}_province\n" if located else ""
        desc = "report_desc" if located else "unlocated_desc"
        output.append(f'''# {title}: short lore report {'with the clicked province' if located else 'without a known province'}.
country_event = {{
    id = {prefix}.{number if located else 100 + number}
    title = {key}_report_title
    desc = {key}_{desc}
    picture = {picture}
    is_triggered_only = yes
{goto}    # Dismiss the information; no rewards or movement.
    option = {{ name = {prefix}_report_close }}
}}

''')
    return "".join(output)


def report_location(prefix: str, function: str, loc: dict) -> str:
    target = prefix + "_province"
    loc[prefix + "_report_location"] = location_text(target)
    loc[prefix + "_report_unowned"] = location_text(target, owned=False)
    loc[prefix + "_report_close"] = "Close"
    return f'''defined_text = {{
    name = {function}
    random = no
    text = {{
        localisation_key = {prefix}_report_location
        trigger = {{ exists = event_target:{target} event_target:{target} = {{ owner = {{ always = yes }} }} }}
    }}
    text = {{ localisation_key = {prefix}_report_unowned trigger = {{ exists = event_target:{target} }} }}
    text = {{ localisation_key = {prefix}_missing_location }}
}}
'''


