def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--game-dir", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = build(args.game_dir)
    for name, data in outputs.items():
        path = ROOT / name
        if args.check:
            assert path.exists() and path.read_bytes() == data, f"Regenerate {name}"
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print(f"{'Verified' if args.check else 'Generated'} {len(outputs)} files; all 24 artifacts covered with source-derived benefits.")


if __name__ == "__main__":
    main()
